#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { existsSync, lstatSync, mkdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const LAB_ID = 'virtuoso_lab';
const MARKER = '.generated-virtuoso-lab';
const ROOT_FILES = ['plugin.json', 'screen.html', 'screen.js', 'settings.html', 'routes.py', 'LICENSE'];

export function transformRuntime(text) {
  return text.replaceAll('virtuoso', LAB_ID)
    .replaceAll('__SS_', '__VIRTUOSO_LAB_').replaceAll('__ss_', '__virtuoso_lab_')
    .replace(/(?<![A-Za-z0-9_])ss-/g, 'virtuoso_lab_ss-').replace(/(?<![A-Za-z0-9_])vir-/g, 'virtuoso_lab_vir-')
    .replace(/Virtuoso(?=Display|Esports|Metal)/g, 'VirtuosoLab')
    .replace(/\.Virtuoso\b/g, '.VirtuosoLab')
    .replace(/\bWebAudioFont\w*/g, name => 'VirtuosoLab' + name)
    // Asset filenames are unchanged; only the classic script's globals are private.
    .replaceAll('VirtuosoLabWebAudioFontPlayer.js', 'WebAudioFontPlayer.js')
    .replace(/(?<![A-Za-z0-9_])_tone_/g, '_virtuoso_lab_tone_').replace(/(?<![A-Za-z0-9_])_drum_/g, '_virtuoso_lab_drum_');
}

function gitFiles(args) {
  return execFileSync('git', ['ls-files', '-z', ...args], { cwd: REPO, encoding: 'utf8' }).split('\0').filter(Boolean);
}

export function buildLab(dist = resolve(REPO, '..', 'virtuoso-lab-dist')) {
  dist = resolve(dist);
  mkdirSync(dist, { recursive: true });
  dist = realpathSync(dist);
  if (dist === REPO || dist.startsWith(REPO + sep)) throw new Error('Lab output must be outside the source checkout');
  const root = join(dist, LAB_ID);
  if (existsSync(root)) {
    if (lstatSync(root).isSymbolicLink() || !existsSync(join(root, MARKER))) throw new Error('Refusing to replace non-generated Lab directory');
    rmSync(root, { recursive: true });
  }
  mkdirSync(root);
  const write = (file, data) => {
    mkdirSync(dirname(join(root, file)), { recursive: true });
    writeFileSync(join(root, file), data);
  };
  const tracked = gitFiles([]);
  // Only source modules may be untracked. Assets must have passed the repository's licensing review.
  const modules = gitFiles(['--cached', '--others', '--exclude-standard', '--', 'src']);
  const files = [...new Set([...ROOT_FILES, ...tracked.filter(p => /^(assets|static)\//.test(p)), ...modules.filter(p => /^src\/.+\.(js|json)$/.test(p))])].sort();
  for (const file of files) {
    if (file.split('/').some(p => ['node_modules', '.git', '__pycache__'].includes(p))) throw new Error('Unsafe runtime path: ' + file);
    const source = join(REPO, file);
    if (!existsSync(source)) throw new Error('Missing runtime file: ' + file);
    if (realpathSync(source) !== source || !lstatSync(source).isFile()) throw new Error('Runtime symlinks are not packaged: ' + file);
    const bytes = readFileSync(source);
    if (file === 'plugin.json') {
      const manifest = JSON.parse(transformRuntime(bytes.toString()));
      manifest.id = LAB_ID;
      manifest.name = 'Virtuoso (Lab)';
      manifest.nav.label = 'Virtuoso (Lab)';
      manifest.nav.screen = LAB_ID;
      manifest.version = String(manifest.version).replace(/[-+].*$/, '') + '-lab.1';
      write(file, JSON.stringify(manifest, null, 2) + '\n');
    } else if (/\.(js|html|py)$/.test(file) && !file.startsWith('assets/')) {
      let text = transformRuntime(bytes.toString());
      if (file === 'screen.js') {
        const version = JSON.parse(readFileSync(join(root, 'plugin.json'))).version;
        text = text.replace(/(const\s+VIRTUOSO_VERSION\s*=\s*)(['"]).*?\2/, `$1'${version}'`);
      }
      if (file === 'screen.html') text = text.replace(/>Virtuoso</g, '>Virtuoso (Lab)<');
      write(file, text);
    } else write(file, bytes);
  }
  for (const file of ['screen.js', 'src/package.json', 'src/core/pitch.js']) {
    if (!existsSync(join(root, file))) throw new Error('Missing module runtime: ' + file);
  }
  write('README.md', readFileSync(join(REPO, 'docs/virtuoso-lab.md')));
  write(MARKER, 'Generated by scripts/cut-lab.mjs; safe to regenerate. No user data.\n');
  const zip = join(dist, LAB_ID + '.zip');
  if (existsSync(zip)) rmSync(zip);
  execFileSync('zip', ['-q', '-r', zip, LAB_ID], { cwd: dist });
  return { root, zip, files };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length && (args.length !== 2 || args[0] !== '--dist')) throw new Error('Usage: node scripts/cut-lab.mjs [--dist <outside-directory>]');
  const result = buildLab(args[1]);
  console.log(`Virtuoso (Lab) generated from working tree (no commit/push):\n${result.root}\n${result.zip}`);
}
